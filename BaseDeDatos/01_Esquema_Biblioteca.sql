-- -----------------------------------------------------------------------------
-- 2. TABLA: ESTUDIANTE
-- Actor principal que solicita préstamos, devoluciones y reservas (CUS01-CUS05)
-- Sanción (CUS02): SUSPENDIDO por exactamente 2 días si devuelve tarde o dañado
-- -----------------------------------------------------------------------------
CREATE TABLE ESTUDIANTE (
    id_estudiante        VARCHAR2(20)  NOT NULL,
    nombres              VARCHAR2(100) NOT NULL,
    apellidos            VARCHAR2(100) NOT NULL,
    correo               VARCHAR2(120) NOT NULL,
    estado_estudiante    VARCHAR2(20)  DEFAULT 'ACTIVO' NOT NULL,
    fecha_fin_suspension DATE          NULL,
    CONSTRAINT PK_ESTUDIANTE PRIMARY KEY (id_estudiante),
    CONSTRAINT UQ_ESTUDIANTE_CORREO UNIQUE (correo),
    CONSTRAINT CK_ESTUDIANTE_ESTADO CHECK (estado_estudiante IN ('ACTIVO', 'SUSPENDIDO'))
);

-- -----------------------------------------------------------------------------
-- 3. TABLA: LIBRO
-- Catálogo bibliográfico general de la biblioteca
-- -----------------------------------------------------------------------------
CREATE TABLE LIBRO (
    id_libro         NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    isbn             VARCHAR2(20)  NOT NULL,
    titulo           VARCHAR2(200) NOT NULL,
    autor            VARCHAR2(150) NOT NULL,
    editorial        VARCHAR2(100) NULL,
    anio_publicacion NUMBER(4)     NULL,
    CONSTRAINT PK_LIBRO PRIMARY KEY (id_libro),
    CONSTRAINT UQ_LIBRO_ISBN UNIQUE (isbn)
);

-- -----------------------------------------------------------------------------
-- 4. TABLA: EJEMPLAR
-- Unidades físicas inventariadas e identificadas por código/QR (CUS01-CUS04)
-- -----------------------------------------------------------------------------
CREATE TABLE EJEMPLAR (
    id_ejemplar       VARCHAR2(30) NOT NULL,
    id_libro          NUMBER       NOT NULL,
    codigo_inventario VARCHAR2(50) NOT NULL,
    estado_ejemplar   VARCHAR2(20) DEFAULT 'DISPONIBLE' NOT NULL,
    estado_fisico     VARCHAR2(20) DEFAULT 'BUENO' NOT NULL,
    CONSTRAINT PK_EJEMPLAR PRIMARY KEY (id_ejemplar),
    CONSTRAINT UQ_EJEMPLAR_INVENTARIO UNIQUE (codigo_inventario),
    CONSTRAINT FK_EJEMPLAR_LIBRO FOREIGN KEY (id_libro)
        REFERENCES LIBRO (id_libro),
    CONSTRAINT CK_EJEMPLAR_ESTADO CHECK (estado_ejemplar IN ('DISPONIBLE', 'PRESTADO', 'RESERVADO', 'MANTENIMIENTO')),
    CONSTRAINT CK_EJEMPLAR_FISICO CHECK (estado_fisico IN ('BUENO', 'DANADO'))
);

-- -----------------------------------------------------------------------------
-- 5. TABLA: PRESTAMO (CUS01, CUS02, CUS04)
-- Registro de préstamos presenciales y por autoservicio QR.
-- Plazo automático de 7 días (SYSDATE + 7). Máximo 3 préstamos activos por alumno.
-- -----------------------------------------------------------------------------
CREATE TABLE PRESTAMO (
    id_prestamo               NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_estudiante             VARCHAR2(20) NOT NULL,
    id_ejemplar               VARCHAR2(30) NOT NULL,
    fecha_prestamo            DATE         DEFAULT SYSDATE NOT NULL,
    fecha_devolucion_esperada DATE         DEFAULT (SYSDATE + 7) NOT NULL,
    fecha_devolucion_real     DATE         NULL,
    canal                     VARCHAR2(20) DEFAULT 'PRESENCIAL' NOT NULL,
    devuelto_danado           CHAR(1)      DEFAULT 'N' NOT NULL,
    estado_prestamo           VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_PRESTAMO PRIMARY KEY (id_prestamo),
    CONSTRAINT FK_PRESTAMO_ESTUDIANTE FOREIGN KEY (id_estudiante)
        REFERENCES ESTUDIANTE (id_estudiante),
    CONSTRAINT FK_PRESTAMO_EJEMPLAR FOREIGN KEY (id_ejemplar)
        REFERENCES EJEMPLAR (id_ejemplar),
    CONSTRAINT CK_PRESTAMO_CANAL CHECK (canal IN ('PRESENCIAL', 'AUTOSERVICIO_QR')),
    CONSTRAINT CK_PRESTAMO_DANADO CHECK (devuelto_danado IN ('S', 'N')),
    CONSTRAINT CK_PRESTAMO_ESTADO CHECK (estado_prestamo IN ('ACTIVO', 'DEVUELTO', 'VENCIDO'))
);

-- -----------------------------------------------------------------------------
-- 6. TABLA: RESERVA_MATERIAL (CUS03)
-- Reserva de material bibliográfico con plazo máximo de recojo de 24h (SYSDATE + 1)
-- -----------------------------------------------------------------------------
CREATE TABLE RESERVA_MATERIAL (
    id_reserva_mat      NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_estudiante       VARCHAR2(20) NOT NULL,
    id_ejemplar         VARCHAR2(30) NOT NULL,
    fecha_reserva       DATE         DEFAULT SYSDATE NOT NULL,
    fecha_limite_recojo DATE         DEFAULT (SYSDATE + 1) NOT NULL,
    estado_reserva      VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
    CONSTRAINT PK_RESERVA_MATERIAL PRIMARY KEY (id_reserva_mat),
    CONSTRAINT FK_RES_MAT_ESTUDIANTE FOREIGN KEY (id_estudiante)
        REFERENCES ESTUDIANTE (id_estudiante),
    CONSTRAINT FK_RES_MAT_EJEMPLAR FOREIGN KEY (id_ejemplar)
        REFERENCES EJEMPLAR (id_ejemplar),
    CONSTRAINT CK_RES_MAT_ESTADO CHECK (estado_reserva IN ('PENDIENTE', 'COMPLETADA', 'EXPIRADA', 'CANCELADA'))
);

-- -----------------------------------------------------------------------------
-- 7. TABLA: CUBICULO (CUS05)
-- Espacios grupales sujetos a control de concurrencia (SELECT ... FOR UPDATE)
-- -----------------------------------------------------------------------------
CREATE TABLE CUBICULO (
    id_cubiculo     VARCHAR2(20) NOT NULL,
    nombre_codigo   VARCHAR2(50) NOT NULL,
    capacidad       NUMBER(2)    DEFAULT 4 NOT NULL,
    estado_cubiculo VARCHAR2(20) DEFAULT 'DISPONIBLE' NOT NULL,
    CONSTRAINT PK_CUBICULO PRIMARY KEY (id_cubiculo),
    CONSTRAINT UQ_CUBICULO_CODIGO UNIQUE (nombre_codigo),
    CONSTRAINT CK_CUBICULO_ESTADO CHECK (estado_cubiculo IN ('DISPONIBLE', 'RESERVADO', 'MANTENIMIENTO'))
);

-- -----------------------------------------------------------------------------
-- 8. TABLA: RESERVA_CUBICULO (CUS05)
-- Reserva de cubículos por máximo 2 horas exactas y 1 reserva activa por día.
-- -----------------------------------------------------------------------------
CREATE TABLE RESERVA_CUBICULO (
    id_reserva_cub    NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_cubiculo       VARCHAR2(20) NOT NULL,
    id_estudiante     VARCHAR2(20) NOT NULL,
    fecha_hora_inicio DATE         DEFAULT SYSDATE NOT NULL,
    fecha_hora_fin    DATE         DEFAULT (SYSDATE + (2/24)) NOT NULL,
    estado_reserva    VARCHAR2(20) DEFAULT 'ACTIVA' NOT NULL,
    CONSTRAINT PK_RESERVA_CUBICULO PRIMARY KEY (id_reserva_cub),
    CONSTRAINT FK_RES_CUB_CUBICULO FOREIGN KEY (id_cubiculo)
        REFERENCES CUBICULO (id_cubiculo),
    CONSTRAINT FK_RES_CUB_ESTUDIANTE FOREIGN KEY (id_estudiante)
        REFERENCES ESTUDIANTE (id_estudiante),
    CONSTRAINT CK_RES_CUB_ESTADO CHECK (estado_reserva IN ('ACTIVA', 'FINALIZADA', 'CANCELADA')),
    CONSTRAINT CK_RES_CUB_DURACION CHECK (
        fecha_hora_fin > fecha_hora_inicio
        AND (fecha_hora_fin - fecha_hora_inicio) <= (2/24 + 0.0001)
    )
);

-- -----------------------------------------------------------------------------
-- 9. ÍNDICES DE RENDIMIENTO PARA CONSULTAS DAO Y CLAVES FORÁNEAS
-- -----------------------------------------------------------------------------
CREATE INDEX IDX_EJEMPLAR_LIBRO       ON EJEMPLAR (id_libro);
CREATE INDEX IDX_EJEMPLAR_ESTADO      ON EJEMPLAR (estado_ejemplar);
CREATE INDEX IDX_PRESTAMO_ESTUDIANTE  ON PRESTAMO (id_estudiante, estado_prestamo);
CREATE INDEX IDX_PRESTAMO_EJEMPLAR    ON PRESTAMO (id_ejemplar, estado_prestamo);
CREATE INDEX IDX_RES_MAT_ESTUDIANTE   ON RESERVA_MATERIAL (id_estudiante, estado_reserva);
CREATE INDEX IDX_RES_MAT_EJEMPLAR     ON RESERVA_MATERIAL (id_ejemplar, estado_reserva);
CREATE INDEX IDX_RES_CUB_ESTUDIANTE   ON RESERVA_CUBICULO (id_estudiante, estado_reserva);
CREATE INDEX IDX_RES_CUB_CUBICULO     ON RESERVA_CUBICULO (id_cubiculo, estado_reserva);
